"""Run:  python -m services.eval tune     choose thresholds on day 1 and store them
         python -m services.eval report   write docs/results/prototype-v0.md and .json"""
import json
import sys

from services.common.config import ROOT, db_path, load_config
from services.common.db import connect, get, put
from services.correlate.engine import PRESETS
from services.eval.metrics import WINDOWS, candidate_histogram, evaluate, load_cases, tune


def pct(x, digits=1):
    return "n/a" if x is None else f"{100 * x:.{digits}f}%"


def ci(r):
    return "n/a" if not r["precision_ci"] else f"{pct(r['precision_ci'][0])} to {pct(r['precision_ci'][1])}"


def main(step: str) -> None:
    cfg, con = load_config(), connect(db_path())
    cases = load_cases(con, cfg)
    validation, test = [c for c in cases if c.day == 0], [c for c in cases if c.day > 0]
    target = cfg["matching"]["target_precision"]

    if step == "tune":
        tuned = {p: tune(validation, p, target) for p in PRESETS}
        put(con, "tuned_all", json.dumps(tuned))
        if tuned["central"] is None:
            print(f"[eval] WARNING: no setting reached {pct(target, 0)} precision on day 1. Using a fallback setting.")
        put(con, "tuned_settings", json.dumps(tuned["central"] or
                                              {"preset": "central", "window": 20, "threshold": 0.75, "margin": 0.10}))
        print(f"[eval] tuned on {len(validation)} validation ghosts: {tuned}")
        return

    tuned = json.loads(get(con, "tuned_all") or "{}")
    rw = cfg["matching"]["reported_window_minutes"]
    near = {c.plaza_id: c.nearest for c in test}
    km = {p["id"]: p["km"] for p in cfg["plazas"]}
    gap = {g: abs(km[g] - km[l]) for g, l in near.items()}
    close = [c for c in test if gap[c.plaza_id] == min(gap.values())]
    e1 = evaluate(test, rw, "reported", scope="nearest")
    e1_variants = [
        ("Nearest legacy plaza only, gantries " + " and ".join(sorted({c.plaza_id for c in close}))
         + f" only ({min(gap.values()):.0f} km away)", evaluate(close, rw, "reported", scope="nearest")),
        ("Nearest legacy plaza only, all gantries", e1),
        ("Both legacy plazas, all gantries", evaluate(test, rw, "reported", scope="both"))]
    hist = candidate_histogram(test, rw)
    where = {"In the window": 0, "At the plaza, but outside the window": 0,
             "At the plaza, but the camera got its make, model, colour or body wrong (or it was over 30 minutes off)": 0,
             "Never identified at the nearest legacy plaza": 0}
    for c in test:
        mine = [k for k in c.pool if k.vrn == c.true_vrn and k.plaza_id == c.nearest]
        key = (list(where)[3] if not c.reachable_nearest else list(where)[2] if not mine
               else list(where)[0] if min(abs(k.offset) for k in mine) <= rw / 2 else list(where)[1])
        where[key] += 1
    e2 = [evaluate(test, w, "reported", scope="nearest") for w in WINDOWS]
    e3 = {p: (evaluate(test, s["window"], "full", s["threshold"], s["margin"], p) if s else None)
          for p, s in tuned.items()}
    stats = json.loads(get(con, "sim_stats"))
    results = {"sim": stats, "validation_ghosts": len(validation), "test_ghosts": len(test),
               "target_precision": target, "tuned": tuned, "e1": e1, "e1_variants": [{"label": a, **b} for a, b in e1_variants],
               "e1_histogram": hist, "e1_where": where, "e2": e2, "e3": e3}
    put(con, "results", json.dumps(results))
    out = ROOT / "docs" / "results"
    out.mkdir(parents=True, exist_ok=True)
    (out / "prototype-v0.json").write_text(json.dumps(results, indent=2), encoding="utf-8")

    cam, n = cfg["camera"], len(test)
    L = ["# Prototype v0 results", "",
         "> **Simulated data.** Every number below comes from invented traffic on a fictional corridor.",
         "> No image was processed. Image similarity comes from an assumed noise model.",
         "> These numbers show how the method behaves under stated assumptions.",
         "> They do not show how it performs on real gantry footage.", "",
         "This file is generated by `python -m services.eval report`. Do not edit it by hand.", "",
         "## 1. What was simulated", "",
         "| Item | Value |", "|---|---|",
         f"| Days | {stats['days']} (day 1 for tuning, days 2 to {stats['days']} for testing) |",
         f"| Trips | {stats['trips']:,} |", f"| Toll crossings | {stats['crossings']:,} |",
         f"| Ghost crossings | {stats['ghost_crossings']:,} (validation {len(validation):,}, test {n:,}) |",
         f"| Test ghosts whose vehicle was identified at any legacy plaza | {e3['central']['reachable'] if e3.get('central') else 0:,} |",
         f"| Test ghosts whose vehicle was identified at the nearest legacy plaza | {e1['reachable']:,} ({pct(e1['reachable'] / n)}) |",
         f"| Camera error assumed | model wrong {pct(cam['p_model_wrong'], 0)}, colour wrong {pct(cam['p_colour_wrong'], 0)}, body wrong {pct(cam['p_body_wrong'], 0)} |",
         "", f"## 2. E1: the reported method ({rw}-minute window, make + model + colour + body)", "",
         "The news report describes a search at a nearby boom-barrier plaza. It does not say what happens when",
         "more than one vehicle matches. This test names a vehicle only when exactly one candidate passes.", "",
         "How many registered vehicles pass the time and attribute gates at the nearest legacy plaza, per ghost:", "",
         "| Candidates | Ghosts | Share |", "|---|---|---|"]
    L += [f"| {k} | {v:,} | {pct(v / n)} |" for k, v in hist.items()]
    L += ["", f"Where the ghost's own vehicle was, relative to the {rw}-minute search at the nearest legacy plaza:", "",
          "| The ghost's own vehicle was | Ghosts | Share |", "|---|---|---|"]
    L += [f"| {k} | {v:,} | {pct(v / n)} |" for k, v in where.items()]
    L += ["", "When the ghost's own vehicle is not in the window, any look-alike that is there alone gets named.",
          "", "When exactly one candidate passes, the method names it. Three ways to run it:", "",
          "| Variant | Ghosts | Named | Correct | Wrong | Precision | 95% interval | Resolution |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {a} | {r['ghosts']:,} | {r['recommend']:,} | {r['correct']:,} | {r['wrong']:,} | {pct(r['precision'])} | {ci(r)} | {pct(r['resolution'])} |"
          for a, r in e1_variants]
    L += ["", "Precision = correct ÷ named. Resolution = correct ÷ ghosts whose vehicle was identified at a legacy plaza that the variant searches.",
          "", "## 3. E2: the reported method at other window widths (nearest legacy plaza, all gantries)", "",
          "| Window (min) | Named | Wrong | Precision | Resolution |", "|---|---|---|---|---|"]
    L += [f"| {r['window']} | {r['recommend']:,} | {r['wrong']:,} | {pct(r['precision'])} | {pct(r['resolution'])} |" for r in e2]
    L += ["", "## 4. E3 and E9: the full method (both legacy plazas; adds image similarity and a margin over the runner-up)", "",
          f"Settings were chosen on day 1 to give the highest resolution with precision of {pct(target, 0)} or more.", "",
          "| Image quality assumed | Same vehicle / look-alike | Window | Threshold | Margin | Named | Wrong | Precision | 95% interval | Resolution |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for p in PRESETS:
        pr, s, r = cam["presets"][p], tuned.get(p), e3.get(p)
        same = 1 / (1 + pr["noise"] ** 2)
        desc = f"about {same:.2f} / {pr['lookalike_cos'] * same:.2f}"
        if not r:
            L.append(f"| {p} | {desc} | no setting reached {pct(target, 0)} on day 1 | | | | | | | |")
        else:
            L.append(f"| {p} | {desc} | {s['window']} | {s['threshold']} | {s['margin']} | {r['recommend']:,} | {r['wrong']:,} | "
                     f"{pct(r['precision'], 2)} | {ci(r)} | {pct(r['resolution'])} |")
    c3 = e3.get("central")
    ok_p = bool(c3) and c3["precision"] >= target
    ok_r = bool(c3) and c3["resolution"] >= 0.5
    L += ["", "\"Same vehicle / look-alike\" is the typical image similarity of two photos of one vehicle, and of two",
          "different vehicles of the same model and colour. Both values are assumptions.", "",
          "## 5. Pass lines (central image quality, test days)", "",
          "| Measure | Pass line | Result | Status |", "|---|---|---|---|",
          f"| Precision of a named match | {pct(target, 0)} or higher on at least 5,000 ghosts | "
          f"{pct(c3['precision'], 2) if c3 else 'n/a'} on {n:,} ghosts (95% interval {ci(c3) if c3 else 'n/a'}) | "
          f"{'Pass on the point value' if ok_p and n >= 5000 else 'Fail'} |",
          f"| Resolution rate | 50% or higher | {pct(c3['resolution']) if c3 else 'n/a'} | {'Pass' if ok_r else 'Fail'} |",
          "| Honest-failure error | 5% or lower | not measured: no plate classifier yet | Open |",
          "| Groundedness of evidence packs | zero ungrounded items | not measured: template text only | Open |",
          "", "## 6. Limits", "",
          "1. The traffic, the registration records and the camera errors are simulated.",
          "2. Image similarity is drawn from an assumed model. Real similarity between two cameras, at night or in rain, is unknown.",
          "3. Each simulated vehicle makes one trip. Repeat offenders (E4, E5) and cloned plates (E6) are not modelled yet.",
          "4. The plate status is assigned by the simulator. No classifier decides it.",
          "5. A named match is a recommendation for a human reviewer. It is not a penalty.", ""]
    (out / "prototype-v0.md").write_text("\n".join(L), encoding="utf-8")
    print(f"[eval] E1 reported method (nearest plaza): precision {pct(e1['precision'])}, resolution {pct(e1['resolution'])}")
    for p in PRESETS:
        r = e3.get(p)
        print(f"[eval] E3 full method ({p}): " + (f"precision {pct(r['precision'], 2)}, resolution {pct(r['resolution'])}, settings {tuned[p]}" if r else "no setting met the target"))
    print(f"[eval] wrote {out / 'prototype-v0.md'}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "report")
